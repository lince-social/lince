use super::*;
use nucleus::trust_analysis::claims::{
    Authorship,
    recipes::{EvaluationState, Mode},
};

impl Engine {
    pub(super) async fn serving_recipe_on(
        &self,
        tx: &mut store::sqlx::Transaction<'_, store::sqlx::Sqlite>,
        person: &str,
        source: &Source,
        actor: Option<&str>,
        now: i64,
    ) -> Result<(Artifact, u64), EngineError> {
        if source.kind != SourceKind::Claim {
            return Err(invalid("Recipe sharing requires a claim recipe Record"));
        }
        self.contact_record_readable_on(tx, &source.record, actor)
            .await?;
        let saved = store::claim_recipes::get_on(tx, &source.record).await?;
        if saved.owner != person || !store::claim_recipes::current_on(tx, &saved).await? {
            return Err(invalid("Serve your own current reviewed claim recipe"));
        }
        let state = store::claim_recipes::state_on(tx, &saved).await?;
        if state.mode == Mode::Paused {
            return Err(invalid("Paused recipes do not serve changing claims"));
        }
        let output = state
            .output
            .ok_or_else(|| invalid("Recompute the recipe before sharing its outputs"))?;
        self.contact_record_readable_on(tx, &output, actor).await?;
        let output = store::profile_claims::get_on(tx, &output).await?;
        let statement = &output.document.statement;
        let Authorship::Generated {
            recipe,
            revision,
            state: evaluation,
            permit,
            ..
        } = &statement.authorship
        else {
            return Err(invalid(
                "The current output must be generated by the reviewed recipe",
            ));
        };
        if output.owner != person
            || recipe != &saved.recipe.permit.recipe
            || *revision != saved.recipe.definition.revision
            || permit.as_ref() != &saved.recipe.permit
            || !self
                .recipe_delegate_current_on(tx, &permit.terms.delegate, true)
                .await?
            || (state.mode == Mode::Revoked
                && (*evaluation != EvaluationState::Revoked || !statement.withdrawn))
            || (state.mode == Mode::Enabled && *evaluation == EvaluationState::Revoked)
            || !store::profile_claims::current_on(tx, person, statement).await?
            || self
                .authenticate_profile_claim_on(tx, &output.document, now)
                .await?
                != IdentityAuthenticity::Accepted
        {
            return Err(invalid(
                "The current output or recipe authorization changed",
            ));
        }
        self.trust_profiles_on(
            tx,
            vec![
                statement.issuer.clone(),
                statement.descriptor.subject.clone(),
            ],
            actor,
        )
        .await?;
        let artifact = Artifact::Claim(output.document);
        artifact.validate(now).map_err(invalid)?;
        Ok((artifact, saved.recipe.definition.revision))
    }

    pub(super) async fn recheck_serving_recipe_on(
        &self,
        tx: &mut store::sqlx::Transaction<'_, store::sqlx::Sqlite>,
        review: &Review,
        snapshot: &Snapshot,
        actor: Option<&str>,
        now: i64,
    ) -> Result<(), EngineError> {
        if review.request.scope == Scope::Recipe {
            let (artifact, version) = self
                .serving_recipe_on(tx, &review.person, &review.request.source, actor, now)
                .await?;
            if artifact != snapshot.artifact || version != snapshot.version {
                return Err(invalid(
                    "The recipe controls or current output changed; retry deliberately",
                ));
            }
        }
        Ok(())
    }
}
