let language = 'pt-BR';

export function t(text, values = {}, locale = language) {
  const translated = locale === 'en' ? text : portuguese[text] ?? text;
  return translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

export function localize(value) {
  language = value === 'en' ? 'en' : 'pt-BR';
  document.documentElement.lang = language;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['aria-label', 'title']) {
    for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
}
