fn capture_pixels(image: &Image) -> Vec<u8> {
    use bevy::render::render_resource::TextureFormat;
    let mut pixels = image.data.as_ref().unwrap().clone();
    match image.texture_descriptor.format {
        TextureFormat::Rgba8Unorm | TextureFormat::Rgba8UnormSrgb => {}
        TextureFormat::Bgra8Unorm | TextureFormat::Bgra8UnormSrgb => {
            for pixel in pixels.chunks_exact_mut(4) {
                pixel.swap(0, 2);
            }
        }
        format => panic!("Unsupported screenshot format: {format:?}"),
    }
    pixels
}

#[derive(Resource)]
struct Demo {
    fixture: tempfile::TempDir,
    output: PathBuf,
    room: Option<Entity>,
    cloud: Option<Entity>,
    proxies: Vec<Entity>,
    images: Vec<Vec<u8>>,
    next: u32,
    waiting: bool,
    started: Instant,
}

fn fixture() -> tempfile::TempDir {
    let directory = tempfile::tempdir().unwrap();
    let mut points = Vec::new();
    let mut add = |position: [f32; 3], scale: [f32; 3], color: [f32; 3]| {
        let mut point = bevy_gaussian_splatting::Gaussian3d::default();
        point.position_visibility.position = position;
        point.position_visibility.visibility = 1.0;
        point.rotation.rotation = [1.0, 0.0, 0.0, 0.0];
        point.scale_opacity.scale = scale;
        point.scale_opacity.opacity = 0.95;
        for (coefficient, color) in point.spherical_harmonic.coefficients.iter_mut().zip(color) {
            *coefficient = (color - 0.5) / 0.2820948;
        }
        points.push(point);
    };
    for x in 0..17 {
        for z in 0..13 {
            let color = if (x + z) % 2 == 0 {
                [0.65, 0.49, 0.28]
            } else {
                [0.48, 0.35, 0.2]
            };
            add(
                [-6.0 + x as f32 * 0.75, -0.02, -4.5 + z as f32 * 0.75],
                [0.4, 0.02, 0.4],
                color,
            );
        }
        for y in 0..5 {
            add(
                [-6.0 + x as f32 * 0.75, y as f32 * 0.75, -4.5],
                [0.4, 0.4, 0.02],
                [0.15, 0.42, 0.75],
            );
        }
    }
    for z in 0..13 {
        for y in 0..5 {
            add(
                [-6.0, y as f32 * 0.75, -4.5 + z as f32 * 0.75],
                [0.02, 0.4, 0.4],
                [0.75, 0.3, 0.12],
            );
            add(
                [6.0, y as f32 * 0.75, -4.5 + z as f32 * 0.75],
                [0.02, 0.4, 0.4],
                [0.15, 0.6, 0.32],
            );
        }
    }
    let cloud = bevy_gaussian_splatting::PlanarGaussian3d::from(points);
    splats::codec::encode(
        &cloud,
        &mut std::fs::File::create(directory.path().join("room.gcloud")).unwrap(),
    )
    .unwrap();
    std::fs::write(directory.path().join("CREDITS.txt"), "Procedural room fixture generated by Lince; no external scan. Gaussian renderer: bevy_gaussian_splatting, MIT.").unwrap();
    directory
}

fn change(world: &mut World, root: Entity, stage: usize) {
    let cloud = world.resource::<Demo>().cloud.unwrap();
    match stage {
        0 => {
            world.get_mut::<View>(root).unwrap().spatial = true;
            assets::frame(world, cloud);
        }
        1 => {
            let visual = world.get::<assets::ImportedScene>(cloud).unwrap().0;
            world.entity_mut(visual).insert(Visibility::Hidden);
        }
        2 => {
            world.get_mut::<View>(root).unwrap().spatial = false;
        }
        3 => {
            let visual = world.get::<assets::ImportedScene>(cloud).unwrap().0;
            world.entity_mut(visual).insert(Visibility::Inherited);
            let room = world.resource::<Demo>().room.unwrap();
            topology::set_position(world, room, DVec3::new(1e9, 140.0, -1e9));
            let mut spatial = topology::spatial(world, room);
            spatial.rotation = DQuat::from_rotation_y(0.55).to_array();
            world.entity_mut(room).insert(spatial);
            rooms::synchronize(world);
            for entity in world.resource::<Demo>().proxies.clone() {
                let local = world.get::<rooms::Member>(entity).unwrap().0.local.clone();
                let expected = model::compose(
                    &Pose {
                        position: [1e9, 140.0, -1e9],
                        rotation: DQuat::from_rotation_y(0.55).to_array(),
                    },
                    &local,
                );
                assert!(
                    (topology::position(world, entity).unwrap()
                        - DVec3::from_array(expected.position))
                    .length()
                        < 1e-6
                );
            }
            world.get_mut::<View>(root).unwrap().spatial = true;
            assets::frame(world, cloud);
        }
        4 => {
            world.get_mut::<rooms::Member>(cloud).unwrap().0.local = Pose {
                position: [80.0, 20.0, -40.0],
                rotation: DQuat::from_rotation_y(0.12).to_array(),
            };
            world.get_mut::<assets::ImportedAsset>(cloud).unwrap().scale = 95.0;
            rooms::synchronize(world);
        }
        5 => {
            let saved = assets::snapshot(world, root);
            let decoded: Vec<assets::SavedAsset> =
                serde_json::from_slice(&serde_json::to_vec(&saved).unwrap()).unwrap();
            let saved = decoded.into_iter().next().unwrap();
            let expected = topology::position(world, cloud).unwrap();
            let expected_rotation = topology::spatial(world, cloud).rotation;
            world.despawn(cloud);
            let restored = saved.restore(world, root).unwrap();
            rooms::synchronize(world);
            assert_eq!(topology::position(world, restored), Some(expected));
            assert_eq!(
                topology::spatial(world, restored).rotation,
                expected_rotation
            );
            world.resource_mut::<Demo>().cloud = Some(restored);
        }
        6 => {
            assets::discard(world, cloud);
            let entities = world.resource::<Demo>().proxies.clone();
            for entity in entities {
                world.despawn(entity);
            }
            let room = world.resource::<Demo>().room.unwrap();
            world.despawn(room);
        }
        _ => {}
    }
}

fn exercise(world: &mut World) {
    assert!(
        world.resource::<Demo>().started.elapsed()
            < Duration::from_secs(if world.contains_resource::<connected::Replay>() {
                900
            } else {
                240
            }),
        "Room appearance replay timed out"
    );
    let root = world
        .query_filtered::<Entity, With<BoxRoot>>()
        .single(world)
        .unwrap();
    let frame = world.resource::<FrameCount>().0;
    if connected::active(world) && frame.is_multiple_of(30) {
        eprintln!(
            "Connected room frame {frame}, elapsed {:?}",
            world.resource::<Demo>().started.elapsed()
        );
    }
    if world
        .get::<lince_sandbox::edit_mode::EditMode>(root)
        .is_none()
    {
        return;
    }
    if world.resource::<Demo>().room.is_none() {
        world
            .get_mut::<lince_sandbox::edit_mode::EditMode>(root)
            .unwrap()
            .enabled = true;
        let room = lince_sandbox::sand_store::spawn_sand(
            world,
            root,
            1,
            lince_sandbox::sand_store::SandKind::Square,
            "Room",
            DVec2::ZERO,
        );
        world.get_mut::<CanvasItem>(room).unwrap().size = Vec2::new(1200.0, 900.0);
        lince_sandbox::token_style::set_overrides(world, room, rooms::boundary_style());
        world.entity_mut(room).insert((
            rooms::Room(default()),
            lince_sandbox::canvas_host::Identity(nucleus::new_uid("placement")),
            topology::Spatial {
                depth: Some(2.0),
                world_pinned: true,
                ..default()
            },
        ));
        let proxies = [model::Role::Floor, model::Role::Wall]
            .map(|role| rooms::create_proxy(world, room, role).unwrap())
            .to_vec();
        world
            .entity_mut(proxies[0])
            .insert(topology::appearance::Light(
                nucleus::canvas::appearance::Light {
                    position: [0.0, 700.0, 400.0],
                    intensity: 80_000.0,
                    range: 2500.0,
                    ..default()
                },
            ));
        let source = world.resource::<Demo>().fixture.path().join("room.gcloud");
        assets::import_into_room(world, room, source).unwrap();
        let mut state = world.resource_mut::<Demo>();
        state.room = Some(room);
        state.proxies = proxies;
        return;
    }
    if world.contains_resource::<cleaning::Replay>() {
        cleaning::exercise(world, root);
        return;
    }
    let stage = world.resource::<Demo>().images.len();
    assert!(
        !world.query::<&Text>().iter(world).any(|text| text
            .0
            .contains("Invalid canvas placement metadata")
            || text.0.contains("Use finite")
            || text.0.contains("canvas recovery")),
        "The live room snapshot rejected placement metadata"
    );
    lince_sandbox::canvas_host::capture(world, root)
        .unwrap()
        .validate()
        .unwrap();
    assert!(
        world
            .query::<&topology::appearance::Light>()
            .iter(world)
            .all(|light| light.0.valid())
    );
    if stage < 7 {
        if world.resource::<Demo>().cloud.is_none() {
            let cloud = world
                .query_filtered::<Entity, (With<assets::ImportedAsset>, With<assets::Ready>)>()
                .iter(world)
                .next();
            let Some(cloud) = cloud else {
                return;
            };
            let mut state = world.resource_mut::<Demo>();
            state.cloud = Some(cloud);
            state.next = frame + 24;
        }
        let cloud = world.resource::<Demo>().cloud.unwrap();
        if world.get::<assets::Ready>(cloud).is_none() {
            return;
        }
    }
    if world.resource::<Demo>().waiting || frame < world.resource::<Demo>().next {
        return;
    }
    if stage == 8 {
        for (shown, hidden) in [(0, 3), (1, 2)] {
            let state = world.resource::<Demo>();
            let changed = state.images[shown]
                .chunks_exact(4)
                .zip(state.images[hidden].chunks_exact(4))
                .filter(|(a, b)| {
                    a.iter()
                        .zip(b.iter())
                        .take(3)
                        .any(|(a, b)| a.abs_diff(*b) > 12)
                })
                .count();
            assert!(
                changed > 400,
                "Room cloud did not contribute enough pixels in stage {shown}: {changed}"
            );
        }
        assert_eq!(
            world.query::<&assets::ImportedAsset>().iter(world).count(),
            0
        );
        assert_eq!(world.query::<&rooms::Member>().iter(world).count(), 0);
        assert_eq!(
            world
                .query::<&topology::physics::Body>()
                .iter(world)
                .count(),
            0
        );
        assert_eq!(
            world
                .query::<&bevy_gaussian_splatting::PlanarGaussian3dHandle>()
                .iter(world)
                .count(),
            0
        );
        println!(
            "Room Gaussian import, 2D/3D pixels, proxies, large-coordinate movement, local calibration, restore and cleanup passed"
        );
        world.write_message(AppExit::Success);
        return;
    }
    let names = [
        "flat",
        "spatial",
        "spatial-without-cloud",
        "flat-without-cloud",
        "moved",
        "calibrated",
        "restored",
        "removed",
    ];
    let output = world
        .resource::<Demo>()
        .output
        .join(format!("room-{}.png", names[stage]));
    world.resource_mut::<Demo>().waiting = true;
    world
        .spawn(Screenshot::primary_window())
        .observe(save_to_disk(output))
        .observe(
            move |event: On<ScreenshotCaptured>, mut commands: Commands| {
                let pixels = capture_pixels(&event.image);
                commands.queue(move |world: &mut World| {
                    world.resource_mut::<Demo>().images.push(pixels);
                    change(world, root, stage);
                    let frame = world.resource::<FrameCount>().0;
                    let mut state = world.resource_mut::<Demo>();
                    state.next = frame + 24;
                    state.waiting = false;
                });
            },
        );
}

fn main() -> AppExit {
    let output = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| "/tmp/lince-shader-artifacts/room-appearance".into());
    std::fs::create_dir_all(&output).unwrap();
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .thread_stack_size(32 * 1024 * 1024)
        .build()
        .unwrap();
    let _guard = runtime.enter();
    let mut app = lince_sandbox::app::interface_app();
    if std::env::args().any(|argument| matches!(argument.as_str(), "--cleaning" | "--connected")) {
        runtime.block_on(cleaning::install(&mut app));
    }
    if std::env::args().any(|argument| argument == "--connected") {
        runtime.block_on(connected::install(&mut app));
    }
    let asset_directory = app.world().resource::<assets::AssetDirectory>().0.clone();
    app.add_plugins(bevy::log::LogPlugin::default())
        .insert_resource(WinitSettings::continuous())
        .insert_resource(Demo {
            fixture: fixture(),
            output,
            room: None,
            cloud: None,
            proxies: Vec::new(),
            images: Vec::new(),
            next: 0,
            waiting: false,
            started: Instant::now(),
        })
        .add_systems(
            Startup,
            |mut commands: Commands, mut windows: Query<&mut Window>| {
                let mut window = windows.single_mut().unwrap();
                window.title = "Room appearance · Gaussian splats and native proxies".into();
                window.resolution.set(1400.0, 850.0);
                commands.spawn((BoxRoot, CanvasView::default()));
            },
        )
        .add_systems(
            Update,
            exercise.after(lince_sandbox::physics::SimulateWorkspaces),
        );
    let result = app.run();
    drop(app);
    let _ = std::fs::remove_dir_all(asset_directory);
    result
}
